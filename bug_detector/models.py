"""Data models for static bug detection and syntax error reporting."""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class Severity(str, Enum):
    """Severity levels for detected issues."""
    ERROR = "ERROR"
    WARNING = "WARNING"
    INFO = "INFO"


class FindingCategory(str, Enum):
    """Categorization of findings."""
    SECURITY = "SECURITY"
    CORRECTNESS = "CORRECTNESS"
    STYLE = "STYLE"
    SYNTAX = "SYNTAX"


class BugFinding(BaseModel):
    """Representation of an individual static analysis finding."""
    rule_id: str = Field(..., description="Unique rule identifier (e.g. SEC001, COR001)")
    rule_name: str = Field(..., description="Human-readable rule name")
    category: FindingCategory = Field(..., description="Category of the finding")
    severity: Severity = Field(..., description="Severity level")
    message: str = Field(..., description="Description of the detected issue")
    line_number: int = Field(..., ge=1, description="1-indexed line number where the issue occurs")
    column_offset: int = Field(0, ge=0, description="0-indexed column offset")
    end_line_number: Optional[int] = Field(None, ge=1, description="Ending line number if known")
    end_column_offset: Optional[int] = Field(None, ge=0, description="Ending column offset if known")
    suggestion: Optional[str] = Field(None, description="Actionable recommendation to fix the issue")
    code_snippet: Optional[str] = Field(None, description="Code snippet where the issue occurred")


class SyntaxErrorInfo(BaseModel):
    """Detailed information regarding a Python syntax or indentation failure."""
    message: str = Field(..., description="Error message from Python parser")
    line_number: int = Field(..., ge=1, description="1-indexed line number where syntax error occurred")
    column_offset: int = Field(0, ge=0, description="Column offset of syntax error")
    end_line_number: Optional[int] = Field(None, ge=1, description="Ending line number if available")
    end_column_offset: Optional[int] = Field(None, ge=0, description="Ending column offset if available")
    line_text: Optional[str] = Field(None, description="Source code line where the error occurred")
    pointer_diagram: Optional[str] = Field(None, description="Formatted diagram indicating error position with caret")


class AnalysisSummary(BaseModel):
    """Summary metrics of the analysis."""
    total_findings: int = 0
    errors: int = 0
    warnings: int = 0
    info: int = 0
    categories: Dict[str, int] = Field(default_factory=dict)


class AnalysisReport(BaseModel):
    """Complete analysis report generated by the engine."""
    source_code: str = Field(..., description="The analyzed source code")
    is_syntax_valid: bool = Field(..., description="Whether source code successfully parsed into AST")
    syntax_error: Optional[SyntaxErrorInfo] = Field(None, description="Syntax error details if parsing failed")
    findings: List[BugFinding] = Field(default_factory=list, description="List of static bug findings")
    summary: AnalysisSummary = Field(default_factory=AnalysisSummary, description="Summary metrics")
    execution_time_ms: float = Field(0.0, description="Execution time in milliseconds")


class ReviewRecord(BaseModel):
    """Persisted review record stored in SQLite."""
    id: str = Field(..., description="Unique review identifier")
    timestamp: str = Field(..., description="ISO-8601 UTC timestamp of the review")
    source_code: str = Field(..., description="Submitted Python source code")
    code_hash: str = Field(..., description="SHA-256 digest of submitted source code")
    is_syntax_valid: bool = Field(..., description="Syntax validity flag")
    syntax_error: Optional[SyntaxErrorInfo] = Field(None, description="Syntax error details if invalid")
    findings: List[BugFinding] = Field(default_factory=list, description="List of detected static bug findings")
    summary: AnalysisSummary = Field(default_factory=AnalysisSummary, description="Summary counts and metrics")
    ai_review: Optional[Dict[str, Any]] = Field(None, description="Optional AI review output, null by default")
    duration_ms: float = Field(0.0, ge=0.0, description="Analysis duration in milliseconds")
